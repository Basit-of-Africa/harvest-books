"use server";
import { revalidatePath } from "next/cache";
import { and, eq } from "drizzle-orm";
import { db, schema } from "@/db";
import { requireBusiness } from "@/lib/auth";
import { accountBelongs } from "@/lib/accounts";
import { BOOKS, isBook, type BookKey } from "@/lib/books";
import { attempt, back, str } from "@/lib/flash";
import { isISODate, r2, toNum, todayISO } from "@/lib/format";
import { GENERATED_CASH, postBookRecord, postDepreciation, postOpening, recordPartyPayment, refreshParty, unpostBookRecord } from "@/lib/posting";

const SOURCE_BOOK: Record<string, string> = { sale: "sales", purchase: "purchases", payroll: "payroll", petty: "petty", asset: "assets", invoice: "invoices" };

/** Rows generated by another record are changed from that record, not here. */
function lockedReason(book: BookKey, row: Record<string, any>): string | null {
  if (book === "cash" && row.sourceType && (GENERATED_CASH as readonly string[]).includes(row.sourceType)) return `This line comes from the ${SOURCE_BOOK[row.sourceType]} book. Change it there.`;
  if (book === "parties" && row.sourceType) return row.sourceType === "invoice" ? "This debtor comes from an e-invoice. Record payments here or on the invoice." : `This balance comes from the ${SOURCE_BOOK[row.sourceType]} book. Change it there.`;
  if (book === "sales" && row.invoiceId) return "This sale was posted from an e-invoice. Issue a credit note to change it.";
  return null;
}

export async function saveEntry(fd: FormData) {
  const book = str(fd, "book");
  if (!isBook(book)) back("/dashboard", "err", "Unknown book.");
  const path = `/books/${book}`;
  const ctx = await requireBusiness("accountant");
  const def = BOOKS[book];
  const id = str(fd, "id");
  const values: Record<string, any> = {};
  for (const f of def.fields) {
    const raw = str(fd, f.key);
    if (f.required && !raw && f.type !== "checkbox") back(path + (id ? `?edit=${id}` : ""), "err", `Fill in ${f.label.replace(/ \(.*\)$/, "").toLowerCase()}.`);
    if (f.type === "number") { if (raw && !Number.isFinite(Number(raw.replace(/,/g, "")))) back(path, "err", `${f.label} must be a number.`); values[f.key] = r2(toNum(raw)); }
    else if (f.type === "date") { if (raw && !isISODate(raw)) back(path, "err", `${f.label} must be a valid date.`); values[f.key] = raw || null; }
    else if (f.type === "checkbox") values[f.key] = fd.get(f.key) === "on";
    else if (f.type === "account") values[f.key] = raw || null;
    else if (f.type === "select") values[f.key] = f.options!.includes(raw) ? raw : f.options![0];
    else values[f.key] = raw;
  }
  if (book === "cash" && !(values.moneyIn > 0) && !(values.moneyOut > 0)) back(path, "err", "Enter money in or money out.");
  if (book === "cash" && values.moneyIn > 0 && values.moneyOut > 0) back(path, "err", "Use one line for money in and another for money out.");
  if (book === "petty" && !(values.topUp > 0) && !(values.amountOut > 0)) back(path, "err", "Enter a top-up or an amount spent.");
  if (book === "inventory" && !(values.qtyIn > 0) && !(values.qtyOut > 0)) back(path, "err", "Enter a quantity in or out.");
  if (book === "assets" && !(values.lifeYears > 0)) back(path, "err", "Useful life must be more than zero years.");
  if (values.accountId && !(await accountBelongs(db, ctx.business.id, values.accountId))) back(path, "err", "Choose an account from the list.");

  const table = def.table as any;
  const res = await attempt(() => db.transaction(async (tx) => {
    let row: any;
    if (id) {
      const [cur] = await tx.select().from(table).where(and(eq(table.id, id), eq(table.businessId, ctx.business.id))).limit(1);
      if (!cur) throw new Error("That entry no longer exists.");
      const why = lockedReason(book, cur);
      if (why) throw new Error(why);
      row = ((await tx.update(table).set({ ...values, example: false }).where(eq(table.id, id)).returning()) as any[])[0];
    } else {
      row = ((await tx.insert(table).values({ ...values, businessId: ctx.business.id, createdBy: ctx.user.id }).returning()) as any[])[0];
    }
    await postBookRecord(tx, ctx.business.id, book, row);
    if (book === "parties") await refreshParty(tx, ctx.business.id, row.id);
  }));
  if (!res.ok) back(path + (id ? `?edit=${id}` : ""), "err", res.error);
  revalidatePath("/", "layout");
  back(path, "ok", id ? "Entry updated." : "Entry added.");
}

export async function deleteEntry(fd: FormData) {
  const book = str(fd, "book"), id = str(fd, "id");
  if (!isBook(book)) back("/dashboard", "err", "Unknown book.");
  const path = `/books/${book}`;
  const ctx = await requireBusiness("accountant");
  const table = BOOKS[book].table as any;
  const res = await attempt(() => db.transaction(async (tx) => {
    const [cur] = await tx.select().from(table).where(and(eq(table.id, id), eq(table.businessId, ctx.business.id))).limit(1);
    if (!cur) return;
    const why = lockedReason(book, cur);
    if (why) throw new Error(why);
    if (book === "parties" && toNum(cur.paid) > 0) throw new Error("Payments are recorded against this balance. Delete those cash book lines first.");
    await unpostBookRecord(tx, ctx.business.id, book, id);
    await tx.delete(table).where(eq(table.id, id));
    if (book === "cash" && cur.sourceType === "party_payment") await refreshParty(tx, ctx.business.id, cur.sourceId);
  }));
  if (!res.ok) back(path, "err", res.error);
  revalidatePath("/", "layout");
  back(path, "ok", "Entry deleted.");
}

export async function saveOpening(fd: FormData) {
  const book = str(fd, "book");
  const ctx = await requireBusiness("accountant");
  const key = book === "petty" ? "pettyFloat" : "cashOpening";
  const value = r2(toNum(str(fd, "value")));
  const date = str(fd, "date");
  const patch: Record<string, any> = { [key]: value };
  if (key === "cashOpening") patch.cashOpeningDate = isISODate(date) ? date : null;
  const res = await attempt(() => db.transaction(async (tx) => {
    const [b] = await tx.update(schema.businesses).set(patch).where(eq(schema.businesses.id, ctx.business.id)).returning();
    await postOpening(tx, b);
  }));
  if (!res.ok) back(`/books/${book}`, "err", res.error);
  revalidatePath("/", "layout");
  back(`/books/${book}`, "ok", "Opening balance saved.");
}

export async function recordPayment(fd: FormData) {
  const ctx = await requireBusiness("accountant");
  const partyId = str(fd, "partyId"), date = str(fd, "date") || todayISO();
  const amount = r2(toNum(str(fd, "amount")));
  const res = await attempt(() => db.transaction(async (tx) => {
    const [p] = await tx.select().from(schema.parties).where(and(eq(schema.parties.id, partyId), eq(schema.parties.businessId, ctx.business.id))).limit(1);
    if (!p) throw new Error("That debtor or creditor no longer exists.");
    if (amount > r2(p.amount - p.paid)) throw new Error(`That is more than the ${p.kind === "Debtor" ? "amount owed" : "amount due"} (${r2(p.amount - p.paid)}).`);
    await recordPartyPayment(tx, ctx.business.id, partyId, amount, date, str(fd, "ref"), ctx.user.id);
  }));
  if (!res.ok) back(`/books/parties?pay=${partyId}`, "err", res.error);
  revalidatePath("/", "layout");
  back("/books/parties", "ok", "Payment recorded in the cash book.");
}

export async function depreciateAll() {
  const ctx = await requireBusiness("accountant");
  const res = await attempt(() => db.transaction((tx) => postDepreciation(tx, ctx.business.id)));
  if (!res.ok) back("/books/assets", "err", res.error);
  revalidatePath("/", "layout");
  back("/books/assets", "ok", `Depreciation to today posted to the journal (total ${res.value.toLocaleString("en-NG")}).`);
}
